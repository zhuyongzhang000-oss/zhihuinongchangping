-- 生成近 30 天的扫码日志（演示首页的扫码趋势图）
INSERT INTO trace_scan_log (code, batch_id, ip, user_agent, scanned_at)
SELECT c.code, c.batch_id, '127.0.0.1', 'seed',
       DATE_SUB(DATE_SUB(NOW(), INTERVAL (s.n * 7) % 30 DAY), INTERVAL (s.n * 37) % 600 MINUTE)
FROM (
    WITH RECURSIVE seq (n) AS (SELECT 0 UNION ALL SELECT n + 1 FROM seq WHERE n < 239)
    SELECT n FROM seq
) s
JOIN trace_code c ON c.id = (s.n % 7) % 4 + 1;

UPDATE trace_code c
SET scan_count   = (SELECT COUNT(*) FROM trace_scan_log l WHERE l.code = c.code),
    last_scan_at = (SELECT MAX(scanned_at) FROM trace_scan_log l WHERE l.code = c.code);
